import { useCallback, useEffect, useState } from 'react'
import { useI18n } from '../i18n'
import type { AgentRunResult, TopicInput } from '../types'

interface Props {
  input: TopicInput
  result: AgentRunResult
  onToast?: (type: 'success' | 'info' | 'error', message: string) => void
}

function buildMarkdown(input: TopicInput, result: AgentRunResult, locale: string): string {
  const isZh = locale === 'zh'
  const top = result.candidates[0]
  const lines: string[] = [
    `# Research Topic Agent - ${isZh ? '选题报告' : 'Research Report'}`,
    '',
    `> ${isZh ? '生成时间' : 'Generated'}: ${new Date().toLocaleString(isZh ? 'zh-CN' : 'en-US')}`,
    '',
    `## ${isZh ? '输入概要' : 'Input Summary'}`,
    '',
    `- **${isZh ? '研究兴趣' : 'Research Interest'}**: ${input.researchInterest}`,
    `- **${isZh ? '问题域' : 'Problem Domain'}**: ${input.problemDomain}`,
    `- **${isZh ? '初步想法' : 'Seed Idea'}**: ${input.seedIdea}`,
    `- **${isZh ? '约束' : 'Constraints'}**: ${input.constraints}`,
    `- **${isZh ? '参与模式' : 'Participation'}**: ${input.participationMode === 'high' ? (isZh ? '高参与共创' : 'High Participation') : (isZh ? '低参与自动' : 'Low Participation')}`,
    '',
    `## ${isZh ? '复杂度与架构' : 'Complexity & Architecture'}`,
    '',
    `- **${isZh ? '复杂度' : 'Complexity'}**: ${result.complexity.score}/100 (${result.complexity.level})`,
    `- **${isZh ? '架构模式' : 'Architecture'}**: ${result.architecture.mode}`,
    `- **${isZh ? '原因' : 'Reason'}**: ${result.architecture.reason}`,
    '',
    `## ${isZh ? '候选路径' : 'Candidate Paths'}`,
    '',
    isZh
      ? '| 路径 | 综合分 | 置信度 | 新颖性 | 可行性 |'
      : '| Path | Score | Confidence | Novelty | Feasibility |',
    '|------|--------|--------|--------|--------|',
  ]

  for (const c of result.candidates) {
    lines.push(`| ${c.id} · ${c.name} | ${c.score} | ${c.confidence} | ${c.novelty} | ${c.feasibility} |`)
  }

  if (top) {
    lines.push(
      '',
      `## ${isZh ? '推荐路径' : 'Recommended Path'}`,
      '',
      `**${top.id} · ${top.name}**`,
      '',
      `- ${isZh ? '核心假设' : 'Hypothesis'}: ${top.hypothesis}`,
      `- ${isZh ? '方法链路' : 'Method'}: ${top.method}`,
      `- ${isZh ? '首个可证伪实验' : 'First Experiment'}: ${top.firstExperiment}`,
      `- ${isZh ? '止损条件' : 'Stop Condition'}: ${top.stopCondition}`,
    )
  }

  lines.push(
    '',
    `## ${isZh ? '7 天行动计划' : '7-Day Action Plan'}`,
    '',
    ...result.recommendation.nextSevenDays.map((d) => `- ${d}`),
    '',
    '---',
    '*Generated by Research Topic Agent*',
  )

  return lines.join('\n')
}

export function ShareExport({ input, result, onToast }: Props) {
  const { t, locale } = useI18n()
  const [copied, setCopied] = useState(false)
  useEffect(() => {
    if (!copied) return
    const timer = window.setTimeout(() => setCopied(false), 2200)
    return () => window.clearTimeout(timer)
  }, [copied])
  const [isExporting, setIsExporting] = useState(false)
  const handleCopy = useCallback(async () => {
    const md = buildMarkdown(input, result, locale)
    try {
      await navigator.clipboard.writeText(md)
      setCopied(true)
      onToast?.('success', t('export.copied'))
    } catch {
      onToast?.('error', t('export.copyFail'))
    }
  }, [input, result, locale, onToast, t])

  const handleDownload = useCallback(() => {
    setIsExporting(true)
    const md = buildMarkdown(input, result, locale)
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `report_${new Date().toISOString().slice(0, 10)}.md`
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
    setIsExporting(false)
    onToast?.('success', t('export.downloaded'))
  }, [input, result, locale, onToast, t])

  return (
    <div className="share-export">
      <button
        className={`btn btn-text ${copied ? 'is-copied' : ''}`}
        onClick={() => void handleCopy()}
        type="button"
        aria-label={t('export.copy')}
      >
        <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
          <rect x="9" y="9" width="13" height="13" rx="2" />
          <path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1" />
        </svg>
        <span aria-live="polite">{copied ? t('inst.copied') : t('export.copy')}</span>{copied && <span className="copy-tick" aria-hidden="true">✓</span>}
      </button>
      <button
        className="btn btn-ghost"
        onClick={handleDownload}
        type="button"
        disabled={isExporting}
        aria-label={t('export.download')}
      >
        <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
          <path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4" />
          <polyline points="7,10 12,15 17,10" />
          <line x1="12" y1="15" x2="12" y2="3" />
        </svg>
        {t('export.download')}
      </button>
    </div>
  )
}
